import fs from "node:fs";
import {sourceNotice} from "./source-notices.mjs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const componentsRoot = path.resolve(scriptDir, "..");
const resourceRoot = path.resolve(componentsRoot, "../resource-svelte/src");
const byNamePath = path.join(resourceRoot, "icons/by-name.ts");
const outputPath = path.join(
    componentsRoot,
    "src/internal/component-icon/builtin-icon-data.ts",
);

const names = [
    "arrow-line-down",
    "arrow-line-left",
    "arrow-line-right",
    "arrow-line-up",
    "arrow-line-up-down",
    "arrow-square-out",
    "arrow-up-right",
    "arrows-down",
    "arrows-down-up",
    "arrows-in-simple",
    "arrows-out-simple",
    "arrows-up",
    "calendar-blank",
    "check",
    "check-circle",
    "clock",
    "close",
    "copy",
    "eye",
    "eye-slash",
    "funnel-simple",
    "minus",
    "moon",
    "plus",
    "rightbar",
    "rightbar-mode",
    "rounded-corner",
    "search",
    "sun",
    "three-dots",
    "trash",
    "user",
    "warning",
    "windowed",
    "x-circle",
];
const extraWeights = new Map([
    ["check-circle", ["fill"]],
    ["warning", ["fill"]],
    ["x-circle", ["fill"]],
]);

const source = fs.readFileSync(byNamePath, "utf8");
const imports = new Map();
for (const match of source.matchAll(/import\s+(\w+)\s+from\s+'([^']+\.svelte)'/g)) {
    imports.set(match[1], match[2]);
}

const defaultsStart = source.indexOf("_byDef = {");
const defaultsEnd = source.indexOf("\n  };", defaultsStart);
if (defaultsStart < 0 || defaultsEnd < 0) {
    throw new Error("Unable to locate resource-svelte default icon map");
}
const defaultsSource = source.slice(defaultsStart, defaultsEnd);
const aliases = new Map();
for (const match of defaultsSource.matchAll(/'([^']+)'\s*:\s*(\w+)/g)) {
    aliases.set(match[1], match[2]);
}

const data = {};
for (const name of names) {
    const alias = aliases.get(name);
    const relativeComponentPath = alias && imports.get(alias);
    if (!relativeComponentPath) {
        throw new Error(`Unable to resolve default component for ${name}`);
    }
    const componentPath = path.resolve(
        path.dirname(byNamePath),
        relativeComponentPath,
    );
    const componentSource = fs.readFileSync(componentPath, "utf8");
    const weightsMatch = componentSource.match(
        /const weights = (\{[\s\S]*?\}) as const;/,
    );
    const viewBoxMatch = componentSource.match(
        /const defaultViewBox = "([^"]+)"/,
    );
    const collectionMatch = componentSource.match(/collection: '([^']+)'/);
    if (!weightsMatch || !viewBoxMatch || !collectionMatch) {
        throw new Error(`Unable to read icon data for ${name}`);
    }
    const usageNameMatch = componentSource.match(/usageName: '([^']+)'/);
    const resourceAssets = path.resolve(componentsRoot, "../resource-base/assets/icons");
    const sourceWeights = Function(`"use strict"; return (${weightsMatch[1]});`)();
    const requiredWeights = ["regular", ...(extraWeights.get(name) ?? [])];
    const weights = Object.fromEntries(
        requiredWeights
            .filter((weight) => sourceWeights[weight])
            .map((weight) => [weight, sourceWeights[weight]]),
    );
    // assets 是生成消费源；不接受组件快照私自改变图形与 viewBox。
    for (const [weight, body] of Object.entries(weights)) {
        const assetPath = path.join(resourceAssets, collectionMatch[1], weight, `${usageNameMatch?.[1]}.svg`);
        const asset = fs.readFileSync(assetPath, "utf8");
        const assetViewBox = asset.match(/viewBox=["']([^"']+)["']/)?.[1];
        const assetBody = asset.replace(/^[\s\S]*?<svg\b[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
        if (assetViewBox !== viewBoxMatch[1] || assetBody.replace(/(?:#000000|#000|black)/g, "currentColor") !== body.trim()) {
            throw new Error(`Icon geometry drift: ${name}/${weight} differs from ${assetPath}`);
        }
    }
    data[name] = {
        sourceCollection: collectionMatch[1],
        viewBox: viewBoxMatch[1],
        weights,
    };
}

const output = `// Generated by scripts/generate-builtin-icons.mjs. Do not edit.\n` +
    `// This checked-in snapshot is shipped by Components and has no runtime dependency on resource-svelte.\n` +
    `import type { ComponentIconWeight } from "../../logic/component-icon";\n\n` +
    `export interface BuiltinIconData {\n    sourceCollection: "snowui" | "phosphor" | "special";\n    viewBox: string;\n    weights: Partial<Record<ComponentIconWeight, string>>;\n}\n\n` +
    `export const BUILTIN_ICON_DATA: Record<string, BuiltinIconData | undefined> = ${JSON.stringify(data, null, 4)};\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, sourceNotice("src/internal/component-icon/builtin-icon-data.ts") + output);
